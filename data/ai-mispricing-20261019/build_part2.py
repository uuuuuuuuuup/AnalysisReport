# 压力系数理由: 算力中后期周期顶部利润, 见报告§2; 静态PE排序工具非DCF, 折现率注释 = 当前无风险利率
rows6 = []
def anchor(code, name, mtype, method, assum, np27):
    sn = snap.get(code, {})
    price = sn.get("price") or px.get(code, {}).get("close")
    mcap = sn.get("mcap_total")
    shares = mcap / price if (mcap and price) else None
    tiers = {}
    for label, k, pe in [("保守", 0.6, 12), ("中性", 0.7, 15), ("乐观", 0.85, 18)]:
        mc = np27 * k * pe
        pxr = mc / shares if shares else None
        prem = round((pxr / price - 1) * 100, 1) if (pxr and price) else None
        tiers[label] = (round(mc), round(pxr, 1) if pxr else None, prem)
    rows6.append([code, name, mtype, method, assum, round(np27, 1),
        tiers["保守"][0], tiers["保守"][1], f"{tiers['保守'][2]}%",
        tiers["中性"][0], tiers["中性"][1], f"{tiers['中性'][2]}%",
        tiers["乐观"][0], tiers["乐观"][1], f"{tiers['乐观'][2]}%",
        price, "折溢价为正=现价高于锚(还需跌); 三档市值单位亿元; np27=东财一致预期(10-19)",
        f"折现率参考: 中国10Y {RF_CN}% (A股) / 美债10Y {RF_US}% (港股); 本锚为静态压力测试排序工具, 非DCF非目标价"])
    return tiers

