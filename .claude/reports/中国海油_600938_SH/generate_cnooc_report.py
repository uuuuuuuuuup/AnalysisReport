def bs_row(item, vals):
    c23, c24, c25, c26 = vals
    d24, p24 = (c24 - c23, pct_change(c24, c23)) if not np.isnan(c24) and not np.isnan(c23) else (np.nan, np.nan)
    d25, p25 = (c25 - c24, pct_change(c25, c24)) if not np.isnan(c25) and not np.isnan(c24) else (np.nan, np.nan)
    d26, p26 = (c26 - c25, pct_change(c26, c25)) if not np.isnan(c26) and not np.isnan(c25) else (np.nan, np.nan)
    return f"| {item} | {fmt_b(c23)} | {fmt_b(c24)} | {fmt_b(d24)} | {fmt_p(p24)} | {fmt_b(c25)} | {fmt_b(d25)} | {fmt_p(p25)} | {fmt_b(c26)} | {fmt_b(d26)} | {fmt_p(p26)} |"


