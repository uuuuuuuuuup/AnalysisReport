def pct_change(cur, prev):
    if np.isnan(cur) or np.isnan(prev) or prev == 0:
        return np.nan
    return (cur - prev) / prev * 100


def fmt_b(x):
    if np.isnan(x):
        return "—"
    return f"{x:,.2f}"


def fmt_p(x):
    if np.isnan(x):
        return "—"
    return f"{x:+.1f}%"


def fair_value_linear(L, r_pct):
    r = r_pct / 100.0
    pv = 0.0
    pv += E1 / (1 + r) ** 1
    pv += E2 / (1 + r) ** 2
    pv += E3 / (1 + r) ** 3
    for t in range(4, 9):
        profit_t = E3 + (L - E3) * (t - 3) / 5.0
        pv += profit_t / (1 + r) ** t
    pv += (L / r) / (1 + r) ** 8
    return pv


