import { chromium } from 'playwright';
const b = await chromium.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome' });
const p = await b.newPage({ viewport: { width: 1600, height: 2200 } });
const errs = [];
p.on('pageerror', e => errs.push('PAGE: ' + e.message));
await p.goto('http://127.0.0.1:8899/', { waitUntil: 'networkidle', timeout: 60000 });
await p.waitForTimeout(4000);
await p.click('.area-tabA .pane-tabs button:nth-child(2)');
await p.waitForTimeout(1500);
const box = await p.locator('#chart-monthly canvas').boundingBox();
console.log('canvas:', Math.round(box.width), 'x', Math.round(box.height));
console.log('JS错误:', errs.length);
errs.slice(0, 5).forEach(e => console.log('  X', e));
await p.screenshot({ path: '/tmp/cal-final.png', fullPage: true });
await b.close();
