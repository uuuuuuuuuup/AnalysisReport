import { chromium } from 'playwright';
const browser = await chromium.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome' });
const page = await browser.newPage({ viewport: { width: 1600, height: 2200 } });
const errors = [];
page.on('console', m => { if (m.type() === 'error') errors.push(m.text()); });
page.on('pageerror', e => errors.push('PAGEERROR: ' + e.message));
await page.goto('http://127.0.0.1:8899/', { waitUntil: 'networkidle', timeout: 60000 });
await page.waitForTimeout(4000);
const news = await page.locator('#news-list .news-item').count();
const newsFirst = await page.locator('#news-list .news-item').first().textContent();
const meta = await page.locator('#news-meta').textContent();
const bdst = await page.locator('#bdst-body').textContent();
const tabs = await page.locator('#news-tabs .index-tab').count();
console.log('新闻条数:', news, '| 标签数:', tabs);
console.log('第一条:', newsFirst ? newsFirst.slice(0, 80) : '(空)');
console.log('meta:', meta);
console.log('宽度卡:', (bdst || '').replace(/\s+/g, ' ').slice(0, 300));
console.log('--- console errors:', errors.length);
errors.slice(0, 10).forEach(e => console.log('  X', e.slice(0, 200)));
await page.screenshot({ path: '/tmp/dashboard-full.png', fullPage: true });
await browser.close();
