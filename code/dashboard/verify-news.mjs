import { chromium } from 'playwright';
const b = await chromium.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome' });
const p = await b.newPage({ viewport: { width: 1500, height: 900 } });
await p.goto('http://127.0.0.1:8899/', { waitUntil: 'networkidle', timeout: 90000 });
await p.waitForTimeout(1500);
await p.evaluate(() => { document.getElementById('loading').style.display = 'none'; });
console.log('新闻渲染条数:', await p.locator('#news-list .news-item').count());
console.log('meta:', await p.locator('#news-meta').textContent());
const first = await p.locator('#news-list .news-item').first().getAttribute('data-url');
console.log('首条链接:', first ? '有' : '无');
await b.close();
