import { chromium } from 'playwright';
const browser = await chromium.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome' });
const page = await browser.newPage();
await page.goto('http://127.0.0.1:8899/', { waitUntil: 'networkidle', timeout: 60000 });
await page.waitForSelector('#news-list .news-item', { timeout: 15000 });
const first = await page.locator('#news-list .news-item').first();
const url = await first.getAttribute('data-url');
const hasLink = await first.evaluate(el => el.classList.contains('news-link'));
console.log('首条 data-url:', url ? url.slice(0, 70) + '…' : '(空)');
console.log('news-link 类:', hasLink, '| 条数:', await page.locator('#news-list .news-item').count());
await browser.close();
